import type { EnglishLearningMode, SentenceLesson } from './courseContent';

type VocabularyTag = readonly [word: string, meaning: string];
type PreA1Row = {
  en: string;
  fa: string;
  pronunciation: string;
  pattern: string;
  vocabulary: readonly VocabularyTag[];
};
type PreA1Dialogue = SentenceLesson['dialogue'];

const row = (
  en: string,
  fa: string,
  pronunciation: string,
  pattern: string,
  ...vocabulary: VocabularyTag[]
): PreA1Row => ({ en, fa, pronunciation, pattern, vocabulary });

function lesson(
  id: string,
  learningMode: EnglishLearningMode,
  title: string,
  subtitle: string,
  situation: string,
  teachingFa: string,
  rows: readonly PreA1Row[],
  dialogue: PreA1Dialogue = [],
): SentenceLesson {
  if (rows.length !== 8) throw new Error(`${id} must contain exactly eight learning items.`);
  const number = id.match(/^prea1-(\d+)/)?.[1];
  if (!number) throw new Error(`Invalid Pre-A1 lesson id: ${id}`);
  return {
    id,
    levelId: -1,
    order: 0,
    learningMode,
    title,
    subtitle,
    situation,
    durationMinutes: learningMode === 'words' ? 7 : 9,
    sentences: rows.map((item, index) => ({
      id: `prea1-${number}-s${index + 1}`,
      en: item.en,
      fa: item.fa,
      pronunciation: item.pronunciation,
      pattern: item.pattern,
      vocabulary: item.vocabulary.map(([word, meaning]) => ({ word, meaning })),
    })),
    dialogue: learningMode === 'sentences' ? dialogue : [],
  };
}

const word = (en: string, fa: string, pronunciation: string, roleFa: string) =>
  row(en, fa, pronunciation, roleFa, [en.toLocaleLowerCase('en-US'), fa]);

