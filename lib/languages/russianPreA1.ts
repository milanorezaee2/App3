export const RUSSIAN_PRE_A1_LESSONS: readonly LearningLesson[] = seeds.map(seed => {
  const lessonId = `ru-pre-${seed.id}`;
  const sentences = seed.rows.map(([text, fa, pronunciation, word, meaning], index) =>
    everydaySentence(`${lessonId}-${String(index + 1).padStart(2, '0')}`, text, fa, pronunciation, [[word, meaning]], index === 0 ? seed.pattern : undefined));
  return everydayLesson(lessonId, seed.title, seed.situation, sentences,
    seed.dialogue.map(([speaker, text, fa]) => ({ speaker, text, fa })), seed.checks, seed.note);
});

export const RUSSIAN_PRE_A1_SUBTITLES: Record<string, string> = Object.fromEntries(seeds.map(seed => [`ru-pre-${seed.id}`, seed.subtitle]));
export const RUSSIAN_PRE_A1_MODULES: readonly string[] = seeds.map(seed => seed.title);
