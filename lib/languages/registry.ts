/**
 * Single source of truth for the languages this app ships.
 *
 * Adding a language means editing THIS file (one entry) and adding its course
 * content module. The build-time scope filter, the language picker, resume
 * routing, static web routes and the CI language checks all read from here, so
 * no other configuration has to be touched.
 *
 * Fields
 *  - id            stable code used in routes (/learn/<id>), scope strings and
 *                  progress storage; must stay lowercase a-z.
 *  - speechLocale  BCP-47 locale handed to the device text-to-speech engine.
 *  - home          landing route for the language dashboard.
 *  - status        'available' = full course, 'starter' = early course,
 *                  'planned' = shown as coming soon.
 */
export type LanguageRegistryEntry = {
  readonly id: string;
  readonly name: string;
  readonly nativeName: string;
  readonly speechLocale: string;
  readonly accent: string;
  readonly description: string;
  readonly status: 'available' | 'starter' | 'planned';
  readonly home: string;
};

