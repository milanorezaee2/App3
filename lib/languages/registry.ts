/** Union of the registered language codes; TypeScript narrows every consumer. */
export type LanguageId = (typeof LANGUAGE_REGISTRY)[number]['id'];

/** Ordered codes, e.g. for route generation and scope parsing. */
export const LANGUAGE_IDS: readonly LanguageId[] = LANGUAGE_REGISTRY.map(entry => entry.id);

export const isLanguageId = (value: unknown): value is LanguageId =>
  typeof value === 'string' && (LANGUAGE_IDS as readonly string[]).includes(value);

/**
 * Build defaults. A language is included everywhere unless it appears in one of
 * these lists, so a new entry needs no extra wiring.
 */
export const NATIVE_SCOPE_EXCLUSIONS: ReadonlySet<string> = new Set(['tr']);
export const ADMIN_SCOPE_IDS: readonly string[] = ['en', 'tr'];
export const STARTS_FROM_ZERO: ReadonlySet<string> = new Set(['de', 'fr', 'es']);

/** Languages that have hand-written route files under app/learn/<id>. */
export const DEDICATED_LANGUAGE_PAGES: ReadonlySet<string> = new Set(['ru']);

export const NATIVE_DEFAULT_SCOPE: readonly LanguageId[] =
  LANGUAGE_IDS.filter(id => !NATIVE_SCOPE_EXCLUSIONS.has(id));
export const ADMIN_DEFAULT_SCOPE: readonly LanguageId[] =
  LANGUAGE_IDS.filter(id => ADMIN_SCOPE_IDS.includes(id));

/** Languages that need a concrete URL generated by the static web export. */
export const STATIC_ROUTE_LANGUAGES: readonly LanguageId[] =
  LANGUAGE_IDS.filter(id => id !== 'en' && !DEDICATED_LANGUAGE_PAGES.has(id));

export function findLanguageEntry(id: string | undefined) {
  return LANGUAGE_REGISTRY.find(entry => entry.id === id);
}
